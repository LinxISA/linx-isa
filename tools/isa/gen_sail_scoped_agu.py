#!/usr/bin/env python3
"""Generate scoped single and paired AGU operand decoding."""

import argparse
import json

from gen_sail_scoped_scalar import CATALOG, ROOT


OUTPUT = ROOT / "isa/sail/model/execute/scoped_scalar_agu.sail"


def field_expression(field):
    pieces = sorted(field["pieces"], key=lambda piece: piece["value_lsb"], reverse=True)
    expression = " @ ".join(
        f"word[{piece['instruction_lsb'] + piece['width'] - 1}..{piece['instruction_lsb']}]"
        for piece in pieces
    )
    return f"({expression})" if len(pieces) > 1 else expression


def render():
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    forms = {row["form_id"]: row for row in catalog["forms"]}
    ids = sorted({row["base_form_id"] for row in catalog["scoped_forms"]})
    lines = [
        "// Generated by tools/isa/gen_sail_scoped_agu.py from the locked PTO catalog.",
        "function decode_scoped_agu(id : bits(8), word : bits(48)) -> option(scoped_agu) = {",
        "  match id {",
    ]
    count = 0
    for code, identity in enumerate(ids):
        row = forms[identity]
        agu = row.get("agu", {})
        if (
            agu.get("action") not in {"Load", "Store", "LoadPair", "StorePair"}
            or agu["address_kind"] not in {"Compressed", "Immediate", "PCRelative", "Register"}
        ):
            continue

        load = agu["action"] in {"Load", "LoadPair"}
        paired = agu["action"] in {"LoadPair", "StorePair"}
        compressed = agu["address_kind"] == "Compressed"
        pcr = agu["address_kind"] == "PCRelative"
        indexed = agu["address_kind"] == "Register"
        update = agu["update_mode"]
        fields = {field["name"]: field for field in row["fields"]}
        if agu["size_bytes"] not in {1, 2, 4, 8} or ((pcr or paired or compressed) and update != "None"):
            raise ValueError(f"unexpected access for {identity}")

        base_field = "SrcL" if load or indexed or compressed else "SrcR"
        base = "0b00000" if pcr else field_expression(fields[base_field])
        expected = set()
        if compressed:
            # C.LWI/C.LDI push T. C.SWI/C.SDI read T#1.
            data_reg = "0b11111" if load else "0b11000"
        elif load:
            reg = fields["RegDst0" if paired or update != "None" else "RegDst"]
            expected.add(reg["name"])
            data_reg = field_expression(reg)
        else:
            reg = fields.get("SrcD", fields.get("SrcL"))
            expected.add(reg["name"])
            data_reg = field_expression(reg)
        if not pcr:
            expected.add(base_field)
        second = "None()"
        if paired:
            second_field = "RegDst1" if load else "SrcD1"
            second = f"Some({field_expression(fields[second_field])})"
            expected.add(second_field)

        index = "None()"
        offset = "0x0000000000000000"
        if indexed:
            modifier = field_expression(fields["SrcRType"])
            index_reg = field_expression(fields["SrcR"])
            shift = f"0b{agu['offset_scale']:06b}"
            expected.update({"SrcR", "SrcRType"})
            if "shamt" in fields:
                shift = f"sail_zero_extend({field_expression(fields['shamt'])}, 6)"
                expected.add("shamt")
            index = f"Some(struct {{ reg = {index_reg}, modifier = {modifier}, shift = {shift} }})"
        else:
            immediate = next(field for field in fields.values() if field["name"].startswith("simm"))
            if immediate["signedness"] != "signed":
                raise ValueError(f"unexpected immediate for {identity}")
            expected.add(immediate["name"])
            offset = f"sail_shiftleft(sail_sign_extend({field_expression(immediate)}, 64), {agu['offset_scale']})"

        writeback = "0b00000"
        if update != "None":
            dst = "RegDst1" if load else "RegDst"
            expected.add(dst)
            writeback = field_expression(fields[dst])
        mode = {"None": "ScopedNoWriteback", "PreIndex": "ScopedPreIndex", "PostIndex": "ScopedPostIndex"}[update]
        if expected != fields.keys():
            raise ValueError(f"unhandled operands for {identity}")

        lines += [
            f"    // {identity}",
            f"    0x{code:02X} => Some(struct {{",
            f"      is_store = {str(not load).lower()}, pcr = {str(pcr).lower()},",
            f"      base_reg = {base}, data_reg = {data_reg}, second_reg = {second},",
            f"      offset = {offset}, index = {index},",
            f"      update = {mode}, writeback_reg = {writeback},",
            f"      size = 0x{agu['size_bytes']:X}, signed_load = {str(agu['signed_load']).lower()}",
            "    }),",
        ]
        count += 1
    if count != 177:
        raise ValueError(f"expected 177 AGU forms, found {count}")
    return "\n".join(lines + ["    _ => None()", "  }", "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit(f"stale scoped Sail AGU output: {OUTPUT}")
    else:
        OUTPUT.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
