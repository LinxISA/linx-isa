#!/usr/bin/env python3
"""Generate the Sail carrier decoder and directed witnesses from the PTO lock."""

from __future__ import annotations

import argparse
from collections import defaultdict
import json
from pathlib import Path

from gen_sail_decode import branch_condition


ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "isa/v0.59/state/pto_scalar_forms.json"
LINX = ROOT / "isa/v0.58/linxisa-v0.58.json"
DECODER = ROOT / "isa/sail/model/decode/scoped_scalar.sail"
WITNESSES = ROOT / "isa/sail/tests/scoped_scalar_witnesses.sail"
SCOPES = {"Private": 0, "IntraCore": 1, "InterCore": 2}
LENGTH_CODES = {16: 0, 32: 1, 48: 2}


def packed(parts: list[dict]) -> tuple[int, int]:
    """PTO parts are listed in stream order, low bits first."""
    mask = match = offset = 0
    for index, part in enumerate(parts):
        width = part["width_bits"]
        part_mask = int(part["mask"], 0)
        part_match = int(part["match"], 0)
        if part["index"] != index or part_match & ~part_mask or part_mask >> width:
            raise ValueError("invalid PTO catalog encoding part")
        mask |= part_mask << offset
        match |= part_match << offset
        offset += width
    return mask, match


def field_value(word: int, field: dict) -> int:
    result = 0
    for piece in field["pieces"]:
        value = (word >> piece["instruction_lsb"]) & ((1 << piece["width"]) - 1)
        result |= value << piece["value_lsb"]
    return result


def validate_carrier(base: dict, scoped: dict) -> int:
    length = base["length_bits"]
    scope = SCOPES[scoped["scope"]]
    mask, match = packed(base["encoding"])
    # A 64-bit carrier has an exact 16-bit prefix, then the original word.
    padding = ((1 << 48) - 1) ^ ((1 << length) - 1)
    prefix = 0x001F | (LENGTH_CODES[length] << 10) | (scope << 8)
    expected = (((mask | padding) << 16) | 0xFFFF, (match << 16) | prefix)
    carrier = packed(scoped["encoding"])
    if (
        sum(part["width_bits"] for part in base["encoding"]) != length
        or scoped["length_bits"] != 64
        or scoped["inner_length_bits"] != length
        or scoped["scope_code"] != scope
        or scoped["mnemonic"] != base["mnemonic"]
        or scoped["constraints"] != base["constraints"]
        or sum(part["width_bits"] for part in scoped["encoding"]) != 64
        or carrier != expected
    ):
        raise ValueError(f"carrier differs from its locked base form: {scoped['form_id']}")
    witness = carrier[1]
    fields = {field["name"]: field for field in scoped["fields"]}
    for constraint in scoped["constraints"]:
        if (
            constraint["operator"] != "one-of"
            or field_value(witness, fields[constraint["field"]]) not in constraint["values"]
        ):
            raise ValueError(f"locked mask/match does not give a legal witness: {scoped['form_id']}")
    return witness


def render() -> tuple[str, str]:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    linx = json.loads(LINX.read_text(encoding="utf-8"))
    bases = {row["form_id"]: row for row in catalog["forms"]}
    compiled = {
        row["pto_source_form_id"]: row
        for row in linx["instructions"]
        if "pto_source_form_id" in row
    }
    scoped_forms: dict[str, list[dict]] = defaultdict(list)
    for row in catalog["scoped_forms"]:
        scoped_forms[row["base_form_id"]].append(row)
    if len(scoped_forms) != 235 or len(catalog["scoped_forms"]) != 705:
        raise ValueError("expected 235 base forms and 705 scoped forms")

    provenance = "// Generated by tools/isa/gen_sail_scoped_scalar.py from the locked PTO v0.59.1.0 catalog."
    decoder = [provenance, ""]
    witnesses = [
        provenance,
        "",
        "function verify_pto_scoped_scalar_witnesses() -> unit = {",
        "  let queues : vector(4, option(bits(64))) = vector_init(4, Some(0x0000000000000000));",
        "  assert(bind_scoped_scalar_queues(0, 0, 1, queues, queues));",
    ]
    form_numbers: dict[int, list[int]] = defaultdict(list)
    for number, (identity, variants) in enumerate(sorted(scoped_forms.items())):
        base = bases[identity]
        length = base["length_bits"]
        item = compiled[identity]
        # The existing Linx decoder owns operand extraction and reserved-value
        # predicates. Confirm the raw predicate before reusing its constraints.
        if item["length_bits"] != length or packed(item["encoding"]["parts"]) != packed(base["encoding"]):
            raise ValueError(f"Linx mask/match differs from the locked base form: {identity}")
        if len(variants) != 3 or {row["scope"] for row in variants} != SCOPES.keys():
            raise ValueError(f"carrier variants are incomplete for {identity}")
        form_numbers[length].append(number)
        decoder.extend([
            f"// {identity}",
            f"function pto_scoped_match_{number}(inst : bits({length})) -> bool = {{",
            f"  {branch_condition(item)}",
            "}",
            "",
        ])
        for row in sorted(variants, key=lambda item: item["scope_code"]):
            witness = validate_carrier(base, row)
            witnesses.append(
                f"  verify_scoped_scalar_witness(0x{witness:016X}, 0x{number:02X});"
            )

    for length, numbers in sorted(form_numbers.items()):
        decoder.append(f"function pto_scoped_inner_{length}(inst : bits({length})) -> bits(8) = {{")
        for index, number in enumerate(numbers):
            keyword = "if" if index == 0 else "else if"
            decoder.append(f"  {keyword} pto_scoped_match_{number}(inst) then 0x{number:02X}")
        decoder.extend(["  else 0xFF", "}", ""])

    decoder.extend([
        "// Input bits are the little-endian instruction stream packed from the first halfword.",
        "// 0xFF rejects the carrier. Other values select a unique locked base form.",
        "function decode_pto_scoped_scalar(inst : bits(64)) -> bits(8) = {",
        "  if (inst[15..0] & 0xF0FF) != 0x001F | inst[9..8] == 0b11 then 0xFF",
        "  else match inst[11..10] {",
        "    0b00 => if inst[63..32] == 0x00000000 then pto_scoped_inner_16(inst[31..16]) else 0xFF,",
        "    0b01 => if inst[63..48] == 0x0000 then pto_scoped_inner_32(inst[47..16]) else 0xFF,",
        "    0b10 => pto_scoped_inner_48(inst[63..16]),",
        "    _ => 0xFF",
        "  }",
        "}",
    ])
    witnesses.extend(["  ()", "}"])
    return ("\n".join(decoder) + "\n", "\n".join(witnesses) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in zip((DECODER, WITNESSES), render(), strict=True):
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                raise SystemExit(f"stale scoped Sail output: {path}")
        else:
            path.write_text(expected, encoding="utf-8")
    print("OK: Sail scoped carrier decoder and 705 witnesses")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
