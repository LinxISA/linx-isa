#!/usr/bin/env python3
"""Generate scoped Scalar AMO operand and transaction decoding."""

import argparse
import json

from gen_sail_scoped_scalar import CATALOG, ROOT


OUTPUT = ROOT / "isa/sail/model/execute/scoped_scalar_atomic.sail"
WITNESSES = ROOT / "isa/sail/tests/scoped_scalar_atomic_witnesses.sail"


def field_expression(field):
    pieces = sorted(field["pieces"], key=lambda piece: piece["value_lsb"], reverse=True)
    expression = " @ ".join(
        f"word[{piece['instruction_lsb'] + piece['width'] - 1}..{piece['instruction_lsb']}]"
        for piece in pieces
    )
    return f"({expression})" if len(pieces) > 1 else expression


def boolean_expression(fields, name):
    return f"{field_expression(fields[name])} == 0b1" if name in fields else "false"


def atomic_operation(mnemonic):
    operation = mnemonic.split(".")[-1]
    if mnemonic.startswith("SWAP"):
        return "ScopedAtomicSwap"
    return {
        "ADD": "ScopedAtomicAdd",
        "SUB": "ScopedAtomicSub",
        "AND": "ScopedAtomicAnd",
        "OR": "ScopedAtomicOr",
        "XOR": "ScopedAtomicXor",
        "SMIN": "ScopedAtomicSmin",
        "SMAX": "ScopedAtomicSmax",
        "UMIN": "ScopedAtomicUmin",
        "UMAX": "ScopedAtomicUmax",
    }.get(operation, "ScopedAtomicSwap")


def access_size(mnemonic):
    operation = mnemonic.split(".")[-1]
    suffix = mnemonic[-1] if operation not in {"ADD", "SUB", "AND", "OR", "XOR", "SMIN", "SMAX", "UMIN", "UMAX"} else mnemonic.split(".")[0][-1]
    return {"B": 1, "H": 2, "W": 4, "D": 8}[suffix]


def render():
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    forms = {row["form_id"]: row for row in catalog["forms"]}
    ids = sorted({row["base_form_id"] for row in catalog["scoped_forms"]})
    private = {row["base_form_id"]: row for row in catalog["scoped_forms"] if row["scope_code"] == 0}
    lines = [
        "// Generated by tools/isa/gen_sail_scoped_atomic.py from the locked PTO catalog.",
        "function decode_scoped_atomic(id : bits(8), word : bits(48)) -> option(scoped_atomic) = {",
        "  match id {",
    ]
    count = 0
    witnesses = [
        "// Generated by tools/isa/gen_sail_scoped_atomic.py from the locked PTO catalog.",
        "function verify_scoped_atomic_witnesses() -> unit = {",
    ]
    for code, identity in enumerate(ids):
        row = forms[identity]
        if row.get("semantic_family") != "AMO":
            continue
        fields = {field["name"]: field for field in row["fields"]}
        handler = row["semantic_handler"]
        mnemonic = row["mnemonic"]
        if handler == "LoadReserved":
            kind, address, operand, compare = (
                "ScopedAtomicLoadReserved",
                fields["SrcL"],
                "None()",
                "None()",
            )
            destination = f"Some({field_expression(fields['RegDst'])})"
            zero_guard = ""
            expected = {"RegDst", "SrcL", "SrcZero", "aq", "far", "rl"}
        elif handler == "StoreConditional":
            kind, address, operand, compare = (
                "ScopedAtomicStoreConditional",
                fields["SrcR"],
                f"Some({field_expression(fields['SrcL'])})",
                "None()",
            )
            destination = f"Some({field_expression(fields['RegDst'])})"
            zero_guard = ""
            expected = {"RegDst", "SrcL", "SrcR", "aq", "far", "rl"}
        elif handler == "CompareAndSwap":
            kind, address, operand, compare = (
                "ScopedAtomicCompareAndSwap",
                fields["SrcL"],
                f"Some({field_expression(fields['SrcD'])})",
                f"Some({field_expression(fields['SrcR'])})",
            )
            destination = f"Some({field_expression(fields['RegDst'])})"
            zero_guard = ""
            expected = {"RegDst", "SrcD", "SrcL", "SrcR", "aq", "rl"}
            if "far" in fields:
                expected.add("far")
        elif handler == "AtomicReadModifyWrite":
            kind, address, operand, compare = (
                "ScopedAtomicReadModifyWrite",
                fields["SrcL"],
                f"Some({field_expression(fields['SrcR'])})",
                "None()",
            )
            destination = f"Some({field_expression(fields['RegDst'])})" if "RegDst" in fields else "None()"
            zero_guard = ""
            expected = {"SrcL", "SrcR", "rl"}
            if "RegDst" in fields:
                expected.update({"RegDst", "aq", "far"})
        else:
            raise ValueError(f"unsupported AMO handler {handler} for {identity}")
        if expected != fields.keys() or row["constraints"]:
            raise ValueError(f"unhandled AMO operands for {identity}: {fields.keys()}")
        aq = boolean_expression(fields, "aq")
        rl = boolean_expression(fields, "rl")
        far = boolean_expression(fields, "far")
        lines += [
            f"    // {identity}",
            f"    0x{code:02X} => {zero_guard}Some(struct {{",
            f"      kind = {kind}, operation = {atomic_operation(mnemonic)},",
            f"      address_reg = {field_expression(address)}, destination = {destination},",
            f"      operand_reg = {operand}, compare_reg = {compare},",
            f"      size = 0x{access_size(mnemonic):X}, acquire = {aq}, release = {rl}, far = {far}",
            "    }),",
        ]
        carrier = private[identity]
        word = offset = 0
        for part in carrier["encoding"]:
            word |= int(part["match"], 0) << offset
            offset += part["width_bits"]
        witnesses.append(
            f"  assert(not_bool(is_none(decode_scoped_atomic(0x{code:02X}, 0x{word >> 16:012X})))); // {identity}"
        )
        count += 1
    if count != 58:
        raise ValueError(f"expected 58 scoped AMO forms, found {count}")
    return (
        "\n".join(lines + ["    _ => None()", "  }", "}", ""]),
        "\n".join(witnesses + ["  ()", "}", ""]),
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in zip((OUTPUT, WITNESSES), render(), strict=True):
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"stale scoped Sail atomic output: {path}")
        else:
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
